interface AdminLocaleContextType {
  locale: AdminLocale;
  setLocale: (loc: AdminLocale) => void;
  toggleLocale: () => void;
  t: (key: keyof typeof adminTranslations.ar) => string;
  isRtl: boolean;
}

const AdminLocaleContext = createContext<AdminLocaleContextType | undefined>(undefined);

export function AdminLocaleProvider({ children }: { children: React.ReactNode }) {
  // Default to Arabic ('ar') as requested by user
  const [locale, setLocaleState] = useState<AdminLocale>('ar');

  useEffect(() => {
    const saved = localStorage.getItem('altayeb_admin_lang') as AdminLocale | null;
    if (saved === 'ar' || saved === 'en') {
      setLocaleState(saved);
    } else {
      setLocaleState('ar');
    }
  }, []);

  const setLocale = (newLocale: AdminLocale) => {
    setLocaleState(newLocale);
    localStorage.setItem('altayeb_admin_lang', newLocale);
  };

  const toggleLocale = () => {
    const next = locale === 'ar' ? 'en' : 'ar';
    setLocale(next);
  };

  const isRtl = locale === 'ar';

  const t = (key: keyof typeof adminTranslations.ar) => {
    return adminTranslations[locale]?.[key] || adminTranslations.ar[key] || key;
  };

  return (
    <AdminLocaleContext.Provider value={{ locale, setLocale, toggleLocale, t, isRtl }}>
      {children}
    </AdminLocaleContext.Provider>
  );
}

export function useAdminLocale() {
  const ctx = useContext(AdminLocaleContext);
  if (!ctx) {
    // Fallback if rendered outside provider
    return {
      locale: 'ar' as AdminLocale,
      setLocale: () => {},
      toggleLocale: () => {},
      t: (key: keyof typeof adminTranslations.ar) => adminTranslations.ar[key] || key,
      isRtl: true,
    };
  }
  return ctx;
}
